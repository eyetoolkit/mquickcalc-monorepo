#!/usr/bin/env node
/**
 * mQuickCalc _redirects generator
 *
 * Reads tools/redirects-data.json and generates _redirects files
 * for the main site. Format is the Cloudflare Pages _redirects format
 * with 301 status (SEO shortlinks).
 *
 * The site-main _redirects also has its extensionless rewrite at the top
 * (e.g. https://mquickcalc.com/length.html -> /length), which we preserve.
 *
 * Usage:
 *   node tools/gen-redirects.mjs               # main site only (77 shortlinks)
 *   node tools/gen-redirects.mjs all           # all three sites (finance/health have no shortlinks)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const DATA_FILE = path.join(__dirname, 'redirects-data.json');
const TARGET = process.argv[2] || 'site-main';

const SITE_ORIGIN = {
  'site-main':    'https://mquickcalc.com',
  'site-finance': 'https://finance.mquickcalc.com',
  'site-health':  'https://health.mquickcalc.com',
};

if (!SITE_ORIGIN[TARGET]) {
  console.error(`❌ Unknown target: ${TARGET}`);
  console.error(`   options: ${Object.keys(SITE_ORIGIN).join(', ')}`);
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'));

const lines = [];
lines.push(`# ${SITE_ORIGIN[TARGET]} - Cloudflare Pages redirects`);
lines.push(`# Auto-generated by tools/gen-redirects.mjs on ${new Date().toISOString().slice(0,10)}`);
lines.push(`# Edit tools/redirects-data.json instead of this file.`);
lines.push('');
lines.push(`${SITE_ORIGIN[TARGET]}/*.html  ${SITE_ORIGIN[TARGET]}/:splat  301`);
lines.push('/tools/currency-converter  /  301');
lines.push('');

// 按 namespace 分组，输出注释块
const byNs = {};
for (const entry of data) {
  byNs[entry.namespace] = byNs[entry.namespace] || [];
  byNs[entry.namespace].push(entry);
}

const namespaces = Object.keys(byNs).sort();
const totalPairs = data.reduce((s, e) => s + e.pairs.length, 0);
lines.push(`# ===== Bidirectional converter shortlinks (SEO) - ${totalPairs} entries (auto-generated)`);

for (const ns of namespaces) {
  const entries = byNs[ns];
  for (const e of entries) {
    for (const [from, target] of e.pairs) {
      // 双向生成 from→target 和 target→from（除非它们指向同一工具）
      lines.push(`  /${ns}/${from}-to-${target}  /tools/${e.tool}?from=${from}&target=${target}  301`);
      // 不生成反向（from-to-target 已经是 SEO 友好的；反向通过工具页面内部 query 即可）
    }
  }
}

const content = lines.join('\n') + '\n';
const outFile = path.join(ROOT, 'packages', TARGET, '_redirects');
fs.writeFileSync(outFile, content);

const urlCount = (content.match(/ 301$/gm) || []).length;
console.log(`   ✅ ${TARGET}: ${urlCount} redirects → ${path.relative(ROOT, outFile)}`);
console.log(`      (${totalPairs} shortlinks across ${namespaces.length} namespaces)`);
